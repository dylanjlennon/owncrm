#!/usr/bin/env node
// Usage: npm run contract:sql <folder> > import.sql
// For large imports: checks the folder, then prints SQL to paste into the Supabase SQL editor.
// It calls the same import function the app uses, so undo works from the Import page.
import { resolve } from 'node:path';
import { readFolder } from './check.mjs';
import { validateContract } from './lib/validate.mjs';

const dir = process.argv[2];
const result = validateContract(readFolder(resolve(dir || '.')));
if (!result.ok) { console.error('Folder is not valid. Run npm run contract:check first.'); process.exit(1); }
const json = JSON.stringify(result.data).replace(/\$owncrm\$/g, '');
process.stdout.write(`-- Generated by contract/to-sql.mjs. Imports ${result.counts.households} households.
with imp as (insert into public.imports (kind, filename) values ('contract', 'SQL import ${new Date().toISOString().slice(0, 10)}') returning id)
select public.import_contract($owncrm$${json}$owncrm$::jsonb, (select id from imp));
`);
